"""
Сервис для работы с g4f (AI-консультант).
"""

import asyncio
import g4f


async def get_ai_answer(question: str) -> str:
    """
    Получение ответа от AI через g4f.
    
    Args:
        question: Вопрос пользователя
    
    Returns:
        Ответ от AI или сообщение об ошибке
    """
    # Системный промпт для контекста
    system_prompt = (
        "Вы — помощник абитуриента белорусских университетов. "
        "Отвечайте на вопросы о поступлении в ВУЗы Беларуси. "
        "Всегда уточняйте, что вы не являетесь официальной приёмной комиссией "
        "и рекомендуете проверять информацию на официальных сайтах ВУЗов. "
        "Отвечайте на русском языке, дружелюбно и информативно."
    )
    
    full_prompt = f"{system_prompt}\n\nВопрос пользователя: {question}"
    
    try:
        # Запускаем g4f в отдельном потоке (он синхронный)
        loop = asyncio.get_event_loop()
        response = await loop.run_in_executor(
            None, 
            lambda: g4f.ChatCompletion.create(
                model="gpt-3.5-turbo",
                messages=[{"role": "user", "content": full_prompt}],
            )
        )
        
        if response:
            return response
        
        return get_fallback_answer()
    
    except Exception as e:
        # Логируем ошибку (в production лучше использовать logging)
        print(f"g4f error: {e}")
        return get_fallback_answer()


def get_fallback_answer() -> str:
    """
    Возвращает запасной ответ если g4f недоступен.
    """
    return (
        "🤖 <b>ИИ-консультант временно недоступен</b>\n\n"
        "К сожалению, сейчас я не могу получить ответ от ИИ-ассистента.\n\n"
        "Попробуйте:\n"
        "• Задать вопрос позже\n"
        "• Записаться на персональную консультацию к куратору\n"
        "• Посетить официальные сайты ВУЗов\n\n"
        "💡 Полезные ресурсы:\n"
        "• abiturient.by — портал для абитуриентов\n"
        "• beluniversitet.by — информация о ВУЗах\n"
        "• Официальные сайты университетов"
    )


def get_quick_answer(question: str) -> str:
    """
    Быстрые ответы на частые вопросы без использования g4f.
    Можно расширить список.
    
    Args:
        question: Вопрос пользователя
    
    Returns:
        Ответ или None если нет быстрого ответа
    """
    question_lower = question.lower()
    
    quick_answers = {
        "когда подават": "Документы обычно подаются с 20 июня по 8 августа. Точные даты уточняйте на сайте ВУЗа!",
        "какие документ": "Обычно нужны: заявление, паспорт, сертификат ЦТ/ЦЭ, аттестат, фото 3x4, медсправка. Уточняйте в приёмной комиссии!",
        "сколько балл": "Минимальный балл зависит от специальности. На бюджет обычно нужно от 250-380 баллов, на платное — меньше.",
        "общаг": "Да, большинство ВУЗов предоставляют общежитие иногородним студентам. Уточняйте условия в конкретном ВУЗе.",
        "платн": "Стоимость обучения на платном зависит от ВУЗа и специальности. Обычно от 1500 до 4000 BYN в год.",
    }
    
    for key, answer in quick_answers.items():
        if key in question_lower:
            return f"💡 <b>Быстрый ответ:</b>\n{answer}\n\n<i>Для более подробной информации запишитесь на консультацию.</i>"
    
    return None
